package com.cardesk.launcher.cluster

/**
 * 仪表歌词的**日夜两套配色**。
 *
 * ## 为什么必须分日夜（第一百三十七轮）
 *
 * 仪表歌词是画在**仪表自己的画面**上的，而仪表的底色也跟着车机的日夜状态走：
 *
 * - **夜间**：仪表底色深（黑 / 深灰）→ 歌词要用**亮色**，浅青 `0xFF7FE3D4` 才看得清；
 * - **日间**：仪表底色是**白色** → 同一支浅青直接**糊进白底里看不见**。
 *
 * 第一百三十三轮刚做出来时只有一套固定配色（浅青 + 浅灰蓝），
 * 那是照着**夜间仪表**调的。日间模式一开，歌词就成了白底上的浅青色 ——
 * 对比度大约 **1.6 : 1**，比正文还难读，用户在真车日间模式下直接反馈「不明显」。
 *
 * 所以这里给日夜各配一套，并且**底板颜色也跟着翻**：
 * 夜间底板是深色（`0x101820`），配亮字；日间底板是浅色（`0xF3F6F9`），配深字。
 * 不翻底板的话，日间模式下「深字 + 深底板」会糊成一片。
 *
 * ## 对比度（WCAG 2.x，实测值见 `ClusterLyricColorsTest`）
 *
 * | 色 | 仪表底 | 对比度 |
 * |---|---|---|
 * | 日间主色 `0xFF0C5F57` | 白 `#FFFFFF` | **7.53 : 1** |
 * | 日间副色 `0xFF46535C` | 白 `#FFFFFF` | **7.92 : 1** |
 * | 夜间主色 `0xFF7FE3D4` | 深 `#0F1116` | **12.45 : 1** |
 * | 夜间副色 `0xFF9FB4BB` | 深 `#0F1116` | **8.74 : 1** |
 *
 * WCAG AA 对正文的要求是 4.5 : 1，四条都过了。
 *
 * ## 对照：第一百三十三轮那套固定配色在白底上有多糟
 *
 * | 色 | 仪表底 | 对比度 |
 * |---|---|---|
 * | 旧主色 `0xFF7FE3D4` | 白 `#FFFFFF` | **1.52 : 1** ✗ |
 * | 旧副色 `0xFF9FB4BB` | 白 `#FFFFFF` | **2.16 : 1** ✗ |
 *
 * 1.52 : 1 连 WCAG AA 的**大字**（3 : 1）都不到 —— 这就是用户说的
 * 「日间模式下白色仪表背景上不明显」的确切数值，不是「感觉不够亮」。
 *
 * ## 第一百四十二轮：底子从「仪表盘面」换成了「高德地图」
 *
 * 第一百三十七轮那套配色隐含一个前提：**字底下是一块纯色仪表盘面**
 * （白天纯白、夜里纯黑）。可实际承载面是**高德地图** ——
 * 导航进画中画之后（第一百三十九/一百四十轮把承载 task 搬到了虚拟屏），
 * 仪表那块屏上画的就是地图。
 *
 * 地图底色不是纯色，而且**每一块都不一样**：
 *
 * | | 日间地图 | 夜间地图 |
 * |---|---|---|
 * | 底色 | 米白 `#F2EFE6` | 深蓝黑 `#0C1018` |
 * | 别的元素 | 绿地 `#D6E8C8`、水系 `#A8D5F0`、白色道路、深色 POI 标签 | 青蓝路网 `#4A6FA5`、浅蓝 POI 字 `#8FA6C0`、金色路名 |
 *
 * 于是两套配色各自踩在一个坑上：
 *
 * - **日间**：深青 `#0C5F57` 压在米白底上够清楚（6.4 : 1），
 *   可地图上**深色 POI 标签**（`#5A6B7A`）和深绿块跟它是同一个明度带 ——
 *   字的轮廓在地图的细节里「陷」进去了，看着就不跳。
 * - **夜间**：浅青 `#7FE3D4` 压在深蓝黑底上够亮（12.4 : 1），
 *   可高德夜间地图**到处都是青蓝色**（路网、POI 图标、路名），
 *   同一个色系的歌词直接混进地图里 —— 这才是「还是不太明显」的真正原因。
 *
 * ## 这一轮怎么改
 *
 * 1. **加对比描边**（[NIGHT_HALO] / [DAY_HALO]）——
 *    字形外圈套一圈与底色**相反**的描边（白天套白边、夜里套黑边）。
 *    这是地图类 UI 的标准做法：**不管字底下是深是浅、是地图还是照片，
 *    字都能立住**。描边宽度按字号自适应，小字（副行）相对更粗。
 * 2. **配色避开地图主色**——
 *    夜间主色从「浅青」提到**更亮更淡的薄荷**（`0xFFA8F7EA`）：
 *    和地图里那些**饱和的**青蓝（`#00C8FF` 那种）拉开距离，
 *    一眼能分出「这是歌词」而不是「这也是地图上的一个青色图标」。
 *    日间主色不动（深青压在米白地图上本来就够清楚），
 *    副色加深一档（`0xFF3B4852`），小字在地图上更立得住。
 *
 * ## 为什么是纯 Kotlin
 *
 * 这一层不碰 Android，**能在 JVM 单测里逐条断言**，
 * 不用起模拟器就能验证「日夜两套都够亮」—— 颜色配错是最容易复发又最难肉眼发现的错。
 */
object ClusterLyricColors {

    // ------------------------------------------------------------ 夜间（地图深底）

    /**
     * 夜间主歌词色：**薄荷白**。
     *
     * 第一百三十三轮是 `0xFF7FE3D4`（浅青）。在高德夜间地图上不够跳 ——
     * 地图里到处是饱和的青蓝元素，同色系的歌词直接混进去。
     * 往「更亮、更淡」推一档之后，和地图里那些青蓝**明度差拉开**，
     * 一眼能分出是歌词。
     */
    const val NIGHT_MAIN = 0xFFA8F7EA.toInt()

    /** 夜间副歌词色：浅灰蓝（上一句 / 下一句），比主色暗一档但仍然够亮。 */
    const val NIGHT_SUB = 0xFFBACBD1.toInt()

    /**
     * 夜间**描边色**：近黑（带一点蓝调，跟夜间地图的色调一致）。
     *
     * 夜里字是亮的，描边就必须是**暗**的 —— 亮字套黑边，
     * 压在地图的深底上不靠描边吃饭，压在地图的**亮色路名/POI 字**上靠它分离。
     */
    const val NIGHT_HALO = 0xF2080B12.toInt()

    /**
     * 夜间底板色（**alpha 恒为 0**，真正的透明度由「仪表背景透明度」滑杆给）。
     *
     * 深色 —— 配夜间的亮字。
     */
    const val NIGHT_PLATE = 0x00101820

    // ------------------------------------------------------------ 日间（地图浅底）

    /**
     * 日间主歌词色：深青。
     *
     * 取的是**同一个色相**（青绿）的深档 —— 夜间薄荷、日间深青，
     * 一眼能看出是同一个强调色在不同底色上的两副面孔，而不是换了个颜色。
     */
    const val DAY_MAIN = 0xFF0C5F57.toInt()

    /** 日间副歌词色：深石板灰（比主色浅一档，但仍然够深）。 */
    const val DAY_SUB = 0xFF3B4852.toInt()

    /**
     * 日间**描边色**：近白。
     *
     * 白天字是暗的，描边就必须是**亮**的 —— 暗字套白边，
     * 压在地图的米白底上不靠描边吃饭，压在地图的**深色 POI 标签/绿块**上靠它分离。
     */
    const val DAY_HALO = 0xF2FFFFFF.toInt()

    /**
     * 日间底板色（alpha 恒为 0）。
     *
     * 浅色 —— 配日间的深字。翻成浅色是必须的：
     * 深字压在深底板上一样看不清。
     */
    const val DAY_PLATE = 0x00F3F6F9

    // ------------------------------------------------------------ 取值

    /** 主歌词色（已唱到部分 + 当前句）。 */
    fun main(night: Boolean): Int = if (night) NIGHT_MAIN else DAY_MAIN

    /** 副歌词色（上一句 / 下一句）。 */
    fun sub(night: Boolean): Int = if (night) NIGHT_SUB else DAY_SUB

    /** 描边色（字形外圈那一圈对比色）。 */
    fun halo(night: Boolean): Int = if (night) NIGHT_HALO else DAY_HALO

    /** 底板色（RGB 部分，alpha 恒为 0）。 */
    fun plate(night: Boolean): Int = if (night) NIGHT_PLATE else DAY_PLATE

    /**
     * 主歌词色最终取值：**用户指定的颜色优先**，否则跟随日夜。
     *
     * @param override 用户在设置页里挑的颜色；`0` = 没挑过 = 跟随日夜。
     */
    fun resolveMain(night: Boolean, override: Int): Int =
        if (override != 0) override else main(night)

    /** 副歌词色最终取值（见 [resolveMain]）。 */
    fun resolveSub(night: Boolean, override: Int): Int =
        if (override != 0) override else sub(night)
}
