package com.cardesk.launcher.cluster

/**
 * 仪表歌词的**日夜两套配色**。
 *
 * ## 为什么必须分日夜（第一百三十七轮）
 *
 * 仪表歌词是画在**仪表自己的画面**上的，而仪表的底色也跟着车机的日夜状态走：
 *
 * - **夜间**：仪表底色深（黑 / 深灰）→ 歌词要用**亮色**，浅青 `0xFF7FE3D4` 才看得清；
 * - **日间**：仪表底色是**白色** → 同一支浅青直接**糊进白底里看不见**。
 *
 * 第一百三十三轮刚做出来时只有一套固定配色（浅青 + 浅灰蓝），
 * 那是照着**夜间仪表**调的。日间模式一开，歌词就成了白底上的浅青色 ——
 * 对比度大约 **1.6 : 1**，比正文还难读，用户在真车日间模式下直接反馈「不明显」。
 *
 * 所以这里给日夜各配一套，并且**底板颜色也跟着翻**：
 * 夜间底板是深色（`0x101820`），配亮字；日间底板是浅色（`0xF3F6F9`），配深字。
 * 不翻底板的话，日间模式下「深字 + 深底板」会糊成一片。
 *
 * ## 对比度（WCAG 2.x，实测值见 `ClusterLyricColorsTest`）
 *
 * | 色 | 仪表底 | 对比度 |
 * |---|---|---|
 * | 日间主色 `0xFF0C5F57` | 白 `#FFFFFF` | **7.53 : 1** |
 * | 日间副色 `0xFF46535C` | 白 `#FFFFFF` | **7.92 : 1** |
 * | 夜间主色 `0xFF7FE3D4` | 深 `#0F1116` | **12.45 : 1** |
 * | 夜间副色 `0xFF9FB4BB` | 深 `#0F1116` | **8.74 : 1** |
 *
 * WCAG AA 对正文的要求是 4.5 : 1，四条都过了。
 *
 * ## 对照：第一百三十三轮那套固定配色在白底上有多糟
 *
 * | 色 | 仪表底 | 对比度 |
 * |---|---|---|
 * | 旧主色 `0xFF7FE3D4` | 白 `#FFFFFF` | **1.52 : 1** ✗ |
 * | 旧副色 `0xFF9FB4BB` | 白 `#FFFFFF` | **2.16 : 1** ✗ |
 *
 * 1.52 : 1 连 WCAG AA 的**大字**（3 : 1）都不到 —— 这就是用户说的
 * 「日间模式下白色仪表背景上不明显」的确切数值，不是「感觉不够亮」。
 *
 * ## 为什么是纯 Kotlin
 *
 * 这一层不碰 Android，**能在 JVM 单测里逐条断言**，
 * 不用起模拟器就能验证「日夜两套都够亮」—— 颜色配错是最容易复发又最难肉眼发现的错。
 */
object ClusterLyricColors {

    // ------------------------------------------------------------ 夜间（仪表深底）

    /** 夜间主歌词色：浅青（第一百三十三轮那套，在深色仪表上够亮）。 */
    const val NIGHT_MAIN = 0xFF7FE3D4.toInt()

    /** 夜间副歌词色：浅灰蓝（上一句 / 下一句）。 */
    const val NIGHT_SUB = 0xFF9FB4BB.toInt()

    /**
     * 夜间底板色（**alpha 恒为 0**，真正的透明度由「仪表背景透明度」滑杆给）。
     *
     * 深色 —— 配夜间的亮字。
     */
    const val NIGHT_PLATE = 0x00101820

    // ------------------------------------------------------------ 日间（仪表白底）

    /**
     * 日间主歌词色：深青。
     *
     * 取的是**同一个色相**（青绿）的深档 —— 夜间浅青、日间深青，
     * 一眼能看出是同一个强调色在不同底色上的两副面孔，而不是换了个颜色。
     */
    const val DAY_MAIN = 0xFF0C5F57.toInt()

    /** 日间副歌词色：深石板灰（比主色浅一档，但仍然够深）。 */
    const val DAY_SUB = 0xFF46535C.toInt()

    /**
     * 日间底板色（alpha 恒为 0）。
     *
     * 浅色 —— 配日间的深字。翻成浅色是必须的：
     * 深字压在深底板上一样看不清。
     */
    const val DAY_PLATE = 0x00F3F6F9

    // ------------------------------------------------------------ 取值

    /** 主歌词色（已唱到部分 + 当前句）。 */
    fun main(night: Boolean): Int = if (night) NIGHT_MAIN else DAY_MAIN

    /** 副歌词色（上一句 / 下一句）。 */
    fun sub(night: Boolean): Int = if (night) NIGHT_SUB else DAY_SUB

    /** 底板色（RGB 部分，alpha 恒为 0）。 */
    fun plate(night: Boolean): Int = if (night) NIGHT_PLATE else DAY_PLATE

    /**
     * 主歌词色最终取值：**用户指定的颜色优先**，否则跟随日夜。
     *
     * @param override 用户在设置页里挑的颜色；`0` = 没挑过 = 跟随日夜。
     */
    fun resolveMain(night: Boolean, override: Int): Int =
        if (override != 0) override else main(night)

    /** 副歌词色最终取值（见 [resolveMain]）。 */
    fun resolveSub(night: Boolean, override: Int): Int =
        if (override != 0) override else sub(night)
}
